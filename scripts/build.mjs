#!/usr/bin/env node
/**
 * Concatenate src/*.css modules into theme.css (release artifact).
 * Order is intentional — do not rely on filesystem sort alone.
 */
import { readFileSync, writeFileSync, watch, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const srcDir = join(root, "src");
const outFile = join(root, "theme.css");

const MODULES = [
  "tokens.css",
  "dark.css",
  "light.css",
  "typography.css",
  "markdown.css",
  "code.css",
  "ui.css",
];

function build() {
  const parts = [
    "/* Idunn — generated by `npm run build`. Edit files under src/, then rebuild. */",
    "",
  ];

  for (const name of MODULES) {
    const path = join(srcDir, name);
    if (!existsSync(path)) {
      console.error(`Missing module: src/${name}`);
      process.exit(1);
    }
    const css = readFileSync(path, "utf8").trimEnd();
    parts.push(`/* === src/${name} === */`, css, "");
  }

  writeFileSync(outFile, parts.join("\n") + "\n", "utf8");
  console.log(`Built ${MODULES.length} modules → theme.css`);
}

build();

if (process.argv.includes("--watch")) {
  console.log("Watching src/ …");
  watch(srcDir, { recursive: false }, (_event, filename) => {
    if (filename && filename.endsWith(".css")) {
      try {
        build();
      } catch (err) {
        console.error(err);
      }
    }
  });
}
